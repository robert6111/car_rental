/** Timezones of a country from PHP's database; the main one first. */
function cr_country_timezones(string $iso): array {
    $list = DateTimeZone::listIdentifiers(DateTimeZone::PER_COUNTRY, $iso);
    $main = cr_countries()[$iso][3] ?? '';
    if ($main !== '' && in_array($main, $list, true)) {
        $list = array_values(array_diff($list, [$main]));
        array_unshift($list, $main);
    }
    return $list;
}
